const evidence={
 schema:'traffic-classroom-bridge-v1',edition:'2026-09-15',inputs,
 projects:PROJECTS.map(p=>({id:p.id,chapter:p.chapter,chapterName:p.chapterName,title:p.title,protocol:p.protocol,cases:CASES.filter(c=>c.chapter===p.chapter).map(c=>({id:c.id,title:c.title}))})),
 forecast:{protocol:reference.protocol,columns:['time','actual','Calendar','Week','ARIMA1','SARIMA1','ARIMA3','SARIMA3','ARIMA6','SARIMA6'],rows:forecast},
 bike:{protocol:'ch04-regression-v1',periods:bikeResults},
 safety:{total:crashes.rows.length,valid:crashes.meta.validCoordinates},
 video:{protocol:video.protocol,source:videoSource,preview:videoPreview,runs:Object.fromEntries(Object.entries(video.runs).map(([k,v])=>[k,{metrics:v.metrics,directions:v.directions,missed_reference:v.missed_reference}]))}
};
